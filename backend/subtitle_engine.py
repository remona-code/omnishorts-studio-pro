def format_ass_time(ms: int) -> str:
    """Formats milliseconds as H:MM:SS.cc for ASS subtitle events."""
    ms = max(0, ms)
    total_cs = ms // 10
    cs = total_cs % 100
    total_sec = total_cs // 100
    s = total_sec % 60
    total_min = total_sec // 60
    m = total_min % 60
    h = total_min // 60
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def escape_ass_text(text: str) -> str:
    return text.replace("\\", "").replace("{", "(").replace("}", ")")


def generate_ass_subtitles(
    scenes: List[SceneItem],
    style_key: str,
    output_ass_path: str,
    play_res_x: int = 720,
    play_res_y: int = 1280,
    skip_first_scene_subtitles: bool = False,
) -> str:
    """
    Generates a complete .ass subtitle file with active-word karaoke highlighting.
    For each chunk of N words, emits one dialogue event per active word so the currently
    spoken word pops in color and scale while surrounding words in the chunk stay visible!
    """
    preset = SUBTITLE_PRESETS.get(style_key, SUBTITLE_PRESETS["hormozi_gold"])
    os.makedirs(os.path.dirname(output_ass_path), exist_ok=True)

    header = f"""[Script Info]
; Generated by OmniShorts Studio Word-Level Karaoke ASS Engine
ScriptType: v4.00+
PlayResX: {play_res_x}
PlayResY: {play_res_y}
ScaledBorderAndShadow: yes
WrapStyle: 2

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: KaraokeMain,{preset['font_name']},{preset['font_size']},{preset['primary_color']},{preset['active_color']},{preset['outline_color']},{preset['back_color']},{preset['bold']},0,0,0,100,100,1.2,0,1,{preset['outline']},{preset['shadow']},2,40,40,{preset['margin_v']},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

    events: List[str] = []
    scene_offset_ms = 0
    chunk_size = preset["words_per_chunk"]
    is_upper = preset["uppercase"]
    primary_c = preset["primary_color"]
    active_c = preset["active_color"]
    emp_c = preset["emphasis_color"]

    for s_idx, sc in enumerate(scenes):
        dur_ms = int(max(1.2, sc.duration_sec) * 1000)
        if not sc.words:
            sc.words = compute_word_timings(sc.narration, start_offset_ms=140, target_duration_sec=sc.duration_sec)

        if skip_first_scene_subtitles and s_idx == 0:
            scene_offset_ms += dur_ms
            continue

        words = sc.words
        for i in range(0, len(words), chunk_size):
            chunk = words[i : i + chunk_size]
            for active_idx, active_wt in enumerate(chunk):
                start_abs = scene_offset_ms + active_wt.start_ms
                # Extend end to the start of the next word in chunk so there's zero flicker
                if active_idx + 1 < len(chunk):
                    end_abs = scene_offset_ms + chunk[active_idx + 1].start_ms
                else:
                    end_abs = scene_offset_ms + active_wt.end_ms + 80

                rendered_tokens = []
                for token_idx, wt in enumerate(chunk):
                    w_txt = escape_ass_text(wt.word.upper() if is_upper else wt.word)
                    if token_idx == active_idx:
                        hl_color = emp_c if wt.emphasis else active_c
                        # Active word pops in color + subtle 110% scale emphasis
                        rendered_tokens.append(
                            f"{{\\1c{hl_color}\\fscx112\\fscy112}}{w_txt}{{\\1c{primary_c}\\fscx100\\fscy100}}"
                        )
                    else:
                        rendered_tokens.append(f"{{\\1c{primary_c}}}{w_txt}")

                line_text = " ".join(rendered_tokens)
                events.append(
                    f"Dialogue: 0,{format_ass_time(start_abs)},{format_ass_time(end_abs)},KaraokeMain,,0,0,0,,{line_text}"
                )

        scene_offset_ms += dur_ms

    with open(output_ass_path, "w", encoding="utf-8") as f:
        f.write(header + "\n".join(events) + "\n")

    return output_ass_path
